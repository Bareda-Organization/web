import { describe, expect, it } from "vitest";
import { waitingDays } from "./waitingDays";

// R50 M6 — 대기 "N일째" 는 24시간 단위가 아니라 서울 달력 날짜로 센다. 신청 당일 = 1일째(O-02 · UF-O-06).
describe("waitingDays", () => {
  it("신청 당일은 몇 시간이 지났든 1일째다", () => {
    expect(waitingDays("2026-10-03T00:05:00+09:00", new Date("2026-10-03T23:50:00+09:00"))).toBe(1);
  });

  it("자정 직전 신청은 다음 날 0시 1분에 2일째다 — 2분이 지났어도 날짜가 바뀌었다", () => {
    expect(waitingDays("2026-10-02T23:59:00+09:00", new Date("2026-10-03T00:01:00+09:00"))).toBe(2);
  });

  it("24시간이 채 안 됐어도 서울 날짜가 이틀 지났으면 3일째다", () => {
    expect(waitingDays("2026-10-01T09:00:00+09:00", new Date("2026-10-03T08:00:00+09:00"))).toBe(3);
  });

  it("서울 날짜로 센다 — UTC 날짜가 아니다(서울 0시 30분 신청은 UTC 로는 전날)", () => {
    // 신청 = 서울 10월 3일 00:30(UTC 10월 2일 15:30) · 지금 = 서울 10월 3일 10:00(UTC 10월 3일 01:00)
    expect(waitingDays("2026-10-02T15:30:00Z", new Date("2026-10-03T01:00:00Z"))).toBe(1);
  });

  it("신청 시각이 지금보다 뒤(시계 어긋남)여도 1일째 밑으로 내려가지 않는다", () => {
    expect(waitingDays("2026-10-04T09:00:00+09:00", new Date("2026-10-03T09:00:00+09:00"))).toBe(1);
  });
});
